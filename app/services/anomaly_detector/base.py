from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional, Tuple
import numpy as np
from pydantic import BaseModel, Field, ConfigDict


class AnomalyRegion(BaseModel):
    """
    Represents an isolated anomaly candidate region generated by an anomaly detection model.
    """
    region_id: str = Field(..., description="Unique ID for this candidate within the image")
    mask: np.ndarray = Field(..., description="Binary 2D mask (uint8, 0 or 255) of the anomaly highlight")
    bbox: Tuple[int, int, int, int] = Field(..., description="(x, y, w, h) bounding rectangle in pixel coordinates")
    anomaly_score: float = Field(..., ge=0.0, le=1.0, description="Confidence/anomaly score from the model")
    confidence_map: Optional[np.ndarray] = Field(default=None, description="Optional raw probability heatmap patch")

    model_config = ConfigDict(arbitrary_types_allowed=True)


class AnomalyDetectionResult(BaseModel):
    """
    Output returned by any AnomalyDetector implementation.
    """
    regions: List[AnomalyRegion] = Field(default_factory=list, description="List of detected candidate regions")
    raw_anomaly_map: Optional[np.ndarray] = Field(default=None, description="Optional full-image anomaly heatmap")
    processing_metadata: Dict[str, Any] = Field(default_factory=dict, description="Model-specific execution metadata")

    model_config = ConfigDict(arbitrary_types_allowed=True)


class AnomalyDetector(ABC):
    """
    Abstract interface for all anomaly detection models.
    Decouples the downstream evidence extraction and API layers from any specific model.
    """

    @abstractmethod
    def predict(
        self,
        image: np.ndarray,
        metadata: Optional[Dict[str, Any]] = None
    ) -> AnomalyDetectionResult:
        """
        Executes anomaly detection on a preprocessed 2D single-channel SSS image.

        Args:
            image: Single-channel uint8 numpy array of shape (H, W).
            metadata: Optional survey/acoustic acquisition metadata.

        Returns:
            AnomalyDetectionResult containing detected regions, masks, and model scores.
        """
        pass
